'use strict';
// Optional development-only dependencies; the app does not require Playwright.
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { start, fakeLocal, root } = require('./helpers');
const { chromium } = process.env.PLAYWRIGHT_MODULE ? require(process.env.PLAYWRIGHT_MODULE) : require('playwright');
const chartFile = path.join(root, 'cockpit/pm2monitor/vendor/chart.umd.js');
async function main() {
    const cleanup = [], context = { after: fn => cleanup.push(fn) };
    let browser;
    try {
        const local = fakeLocal('deploy', [{ id: 0, name: '<img src=x onerror="window.__xss=1">', status: 'stopped', memory: 45 }]);
        const single = await start(context, { local });
        const remote = await start(context, { user: 'appuser', uid: 2000 });
        const main = await start(context, { mode: 'multi-user', local: fakeLocal('deploy', [{ id: 0, name: 'Local process', status: 'stopped', memory: 45 }]) });
        browser = await chromium.launch({ headless: true });
        const page = await browser.newPage({ viewport: { width: 1100, height: 900 } });
        const errors = []; page.on('pageerror', err => errors.push(err.message));
        await page.route('https://cdn.jsdelivr.net/npm/chart.js', route => route.fulfill({ path: chartFile, contentType: 'application/javascript' }));
        await page.route(/https:\/\/(fonts\.googleapis\.com|fonts\.gstatic\.com|cdnjs\.cloudflare\.com)\//, route => route.fulfill({ body: '', contentType: 'text/css' }));
        await page.goto(single.url);
        await page.waitForSelector('.app-card');
        assert.equal(await page.locator('#toolbar').isVisible(), false);
        assert.equal(await page.locator('#memDetail').textContent(), '2.0 / 8.0 GB');
        await page.evaluate(() => renderStats({ cpuUsage: 68, loadPercent: 2, load: .2, totalMem: 8, freeMem: 3, disk: { percent: 20, used: 2, total: 10 } }));
        assert.equal(await page.locator('#cpuVal').textContent(), '68.0%');
        assert.equal(await page.locator('#memVal').textContent(), '62.5%');
        assert.equal(await page.locator('#memDetail').textContent(), '5.0 / 8.0 GB');
        const animation = await page.evaluate(() => {
            const chart = Chart.getChart(document.getElementById('cpuMiniChart'));
            return { duration: chart.options.animation.duration, easing: chart.options.animation.easing, last: chart.data.datasets[0].data.at(-1) };
        });
        assert.deepEqual(animation, { duration: 500, easing: 'easeOutQuart', last: 68 });
        assert.equal(await page.locator('.app-card img').count(), 0);
        assert.equal(await page.evaluate(() => window.__xss), undefined);
        assert.equal(await page.getByRole('button', { name: 'Start', exact: true }).count(), 0);
        await page.locator('#authArea button').click(); await page.locator('#adminPass').fill('test-admin'); await page.locator('#submitLogin').click();
        await page.getByRole('button', { name: 'Start', exact: true }).click();
        await page.getByRole('button', { name: 'Restart', exact: true }).waitFor();
        assert.equal(await page.getByRole('button', { name: 'Start', exact: true }).count(), 0);
        await page.getByRole('button', { name: 'Stop', exact: true }).click(); await page.getByRole('button', { name: 'Start', exact: true }).waitFor();
        await fs.mkdir(path.join(root, 'test-artifacts'), { recursive: true });
        await page.screenshot({ path: path.join(root, 'test-artifacts/single-user.png'), fullPage: true });
        await page.goto(main.url); await page.waitForSelector('.app-card');
        assert.equal(await page.locator('#manageTargets').isVisible(), false);
        await page.locator('#authArea button').click(); await page.locator('#adminPass').fill('test-admin'); await page.locator('#submitLogin').click();
        await page.locator('#manageTargets').click();
        await page.locator('#targetUser').fill('appuser'); await page.locator('#targetPort').fill(new URL(remote.url).port);
        await page.locator('#targetPassword').fill('wrong'); await page.locator('#saveTarget').click();
        await page.waitForFunction(() => document.getElementById('targetMessage').textContent.includes('rejected'));
        assert.equal(main.store.targets.length, 0);
        await page.locator('#targetPassword').fill('test-admin'); await page.locator('#saveTarget').click();
        await page.waitForFunction(() => document.getElementById('targetMessage').textContent === 'Target saved.');
        assert.equal(await page.locator('#targetPassword').inputValue(), '');
        await page.getByRole('button', { name: 'Edit', exact: true }).click();
        assert.equal(await page.locator('#targetPassword').inputValue(), ''); await page.locator('#saveTarget').click();
        await page.waitForFunction(() => document.getElementById('targetMessage').textContent === 'Target saved.');
        await page.locator('#closeTargets').click();
        const remoteCard = page.locator('.app-card[data-user="appuser"]');
        await remoteCard.waitFor();
        await remoteCard.getByRole('button', { name: 'Start', exact: true }).click();
        await remoteCard.getByRole('button', { name: 'Restart', exact: true }).waitFor();
        assert.equal(remote.local.calls.at(-1).action, 'start'); assert.equal(main.local.calls.length, 0);
        await remoteCard.getByRole('button', { name: 'Info / Logs', exact: true }).click();
        await page.waitForFunction(() => document.getElementById('detLogOut').textContent.includes('appuser:0'));
        const remoteChart = await page.evaluate(() => Chart.getChart(document.getElementById('detChart')).data.datasets[0].data.at(-1)); assert.equal(remoteChart, 12);
        await page.locator('#modalActionArea').getByRole('button', { name: 'Close', exact: true }).click();
        await page.locator('.app-card[data-user="deploy"]').getByRole('button', { name: 'Info / Logs', exact: true }).click();
        await page.waitForFunction(() => document.getElementById('detLogOut').textContent.includes('deploy:0'));
        const localChart = await page.evaluate(() => Chart.getChart(document.getElementById('detChart')).data.datasets[0].data.at(-1)); assert.equal(localChart, 45);
        await page.locator('#modalActionArea').getByRole('button', { name: 'Close', exact: true }).click();
        await page.locator('#userFilter').selectOption('appuser'); assert.equal(await page.locator('.app-card').count(), 1);
        await page.locator('#userFilter').selectOption(''); assert.equal(await page.locator('.app-card').count(), 2);
        await page.screenshot({ path: path.join(root, 'test-artifacts/multi-user.png'), fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
        await page.locator('#manageTargets').click();
        page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', { name: 'Remove target', exact: true }).click();
        await page.waitForFunction(() => document.querySelectorAll('#targetsList .target-row').length === 0);
        await page.locator('#closeTargets').click(); await page.locator('#authArea button').click();
        await page.waitForFunction(() => document.getElementById('manageTargets').hidden);
        assert.deepEqual(errors, []);
        console.log('PASS: Chromium UI in both modes, admin-only targets, add/edit/remove, password masking, start/stop/restart, duplicate-ID logs/charts, safe text, mobile layout');
    } finally {
        if (browser) await browser.close();
        for (const fn of cleanup.reverse()) await fn();
    }
}
main().catch(err => { console.error(err); process.exitCode = 1; });
